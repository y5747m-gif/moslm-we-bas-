import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(join(root, "config/alarm-engine.json"), "utf8"));
const grace = Number(config.defaultGraceMinutes);
const maxRing = Number(config.maxRingMinutes);
const version = Number(config.engineVersion);
const durations = config.allowedDurations.map(Number);
if (!Number.isInteger(grace) || grace <= 0 || !Number.isInteger(maxRing) || maxRing <= 0 || !Number.isInteger(version)) {
  throw new Error("Invalid alarm-engine.json");
}
const ts = `// GENERATED by scripts/generate-alarm-constants.mjs — do not edit.\nexport const ALARM_ENGINE_VERSION = ${version};\nexport const DEFAULT_GRACE_MINUTES = ${grace};\nexport const MAX_RING_MINUTES = ${maxRing};\nexport const ALLOWED_DURATIONS = ${JSON.stringify(durations)} as const;\n`;
const java = `package com.hatsally.app;\n\n/** GENERATED from config/alarm-engine.json — do not edit. */\npublic final class AlarmConstants {\n    public static final int ENGINE_VERSION = ${version};\n    public static final int DEFAULT_GRACE_MINUTES = ${grace};\n    public static final int MAX_RING_MINUTES = ${maxRing};\n    public static final int[] ALLOWED_DURATIONS = new int[] { ${durations.join(", ")} };\n    private AlarmConstants() {}\n}\n`;
const sw = `// GENERATED from config/alarm-engine.json — do not edit.\nself.HATSALLY_ALARM_CONFIG = Object.freeze({ engineVersion: ${version}, defaultGraceMinutes: ${grace}, maxRingMinutes: ${maxRing} });\n`;
writeFileSync(join(root, "lib/alarmConstants.ts"), ts);
writeFileSync(join(root, "android/app/src/main/java/com/hatsally/app/AlarmConstants.java"), java);
writeFileSync(join(root, "public/alarm-engine-config.js"), sw);
console.log(`Generated alarm constants v${version}, grace=${grace}, maxRing=${maxRing}`);
